// @vitest-environment node
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';

import { hexToBytes } from '@noble/hashes/utils.js';
import { expect, it } from 'vitest';

import { loadFramedSyncFileInboundBody } from '../../lib/core/sync/framedSyncFileInboundBodies.js';
import { readFramedSyncFileInbound } from '../../lib/core/sync/framedSyncFileInboundRecord.js';
import { loadFramedSyncFileReadySource, streamFramedSyncFileReadySourceFacts } from '../../lib/core/sync/framedSyncFileReadySource.js';

import { createDesktopFramedSyncFiles } from './desktopFramedSyncFiles.js';

it('reads the native iOS receiver files through the shared verified source without a staging database', async () => {
  const root = await mkdtemp(path.join(os.tmpdir(), 'foliole-native-files-'));
  try {
    const files = createDesktopFramedSyncFiles(root);
    // Generated by FolioleFramedSyncFileStorageTests using the native crypto/receiver/file writer.
    const fixture = JSON.parse(await readFile('lib/core/sync/fixtures/framed-sync-ios-files.json', 'utf8')) as Record<string, string>;
    for (const [key, base64] of Object.entries(fixture)) await files.write(key, Buffer.from(base64, 'base64'));
    const [id] = await files.list('inbound');
    const transferId = hexToBytes(id!);
    const record = await readFramedSyncFileInbound(files, transferId);
    expect(record?.state).toBe('ready_to_apply');
    const source = await loadFramedSyncFileReadySource(files, { ...record!.proposal, manifestHash: record!.verifiedManifest! });
    expect(source).not.toBeNull();
    const facts = [];
    for await (const entry of streamFramedSyncFileReadySourceFacts(files, source!)) facts.push(entry.fact);
    expect(facts).toHaveLength(1);
    expect(facts[0]).toMatchObject({ factId: 'original-version', globalId: 'original-body', kind: 2 });
    const blob = record!.header!.blobs[0]!;
    const body = await loadFramedSyncFileInboundBody(files, { transferId, attemptId: record!.header!.attemptId }, blob);
    expect(new TextDecoder().decode(body)).toBe('File-owned native body');
    await files.write(`inbound/${id}/${Buffer.from(record!.header!.attemptId).toString('hex')}/bodies/${Buffer.from(blob.sha256).toString('hex')}.body`,
      new TextEncoder().encode('corrupt'));
    await expect(loadFramedSyncFileReadySource(files, { ...record!.proposal, manifestHash: record!.verifiedManifest! })).rejects.toThrow();
  } finally { await rm(root, { recursive: true, force: true }); }
});
